"""Build the static frontend with its public API origin injected at build time."""

import json
import os
import shutil
import sys
from pathlib import Path
from urllib.parse import urlsplit


def main() -> None:
    api_url = os.getenv("PROJECT_GUARD_API_BASE_URL", "").strip()
    if not api_url:
        raise SystemExit("PROJECT_GUARD_API_BASE_URL must be set to the deployed HTTPS API origin.")
    parsed = urlsplit(api_url)
    try:
        port = parsed.port
    except ValueError as error:
        raise SystemExit("PROJECT_GUARD_API_BASE_URL has an invalid port.") from error
    if (
        parsed.scheme != "https"
        or not parsed.hostname
        or parsed.username
        or parsed.password
        or parsed.path not in ("", "/")
        or parsed.query
        or parsed.fragment
    ):
        raise SystemExit("PROJECT_GUARD_API_BASE_URL must be an HTTPS origin without a path, query, or fragment.")
    hostname = parsed.hostname.lower()
    if ":" in hostname:
        hostname = f"[{hostname}]"
    normalized_origin = f"https://{hostname}" + (f":{port}" if port is not None else "")

    clerk_host = os.getenv("PROJECT_GUARD_CLERK_FAPI_HOST", "").strip().lower()
    clerk_url = urlsplit(f"https://{clerk_host}")
    try:
        clerk_port = clerk_url.port
    except ValueError as error:
        raise SystemExit("PROJECT_GUARD_CLERK_FAPI_HOST must be a hostname only.") from error
    if (
        not clerk_host
        or clerk_url.hostname != clerk_host
        or clerk_port is not None
        or clerk_url.path
        or clerk_url.query
        or clerk_url.fragment
        or "*" in clerk_host
    ):
        raise SystemExit("PROJECT_GUARD_CLERK_FAPI_HOST must be the exact Clerk Frontend API hostname, without scheme or path.")

    source = Path(__file__).resolve().parent / "Frontend"
    output = Path(sys.argv[1] if len(sys.argv) > 1 else "dist").resolve()
    output.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source, output, dirs_exist_ok=True)
    config = output / "deployment-config.js"
    config.write_text(
        "// Generated by build_frontend.py. Contains a public URL only.\n"
        f"window.PROJECT_GUARD_API_BASE_URL = {json.dumps(normalized_origin)};\n",
        encoding="utf-8",
    )
    csp = "; ".join((
        "default-src 'self'",
        "base-uri 'self'",
        "object-src 'none'",
        "frame-ancestors 'none'",
        "form-action 'self'",
        f"script-src 'self' https://{clerk_host} https://challenges.cloudflare.com https://*.protect.clerk.com",
        "script-src-attr 'none'",
        f"connect-src 'self' {normalized_origin} https://{clerk_host} https://*.protect.clerk.com:* https://clerk-telemetry.com https://*.clerk-telemetry.com",
        "img-src 'self' data: https://img.clerk.com",
        f"font-src 'self' data: https://{clerk_host}",
        "style-src 'self' 'unsafe-inline'",
        f"frame-src 'self' https://{clerk_host} https://challenges.cloudflare.com https://*.protect.clerk.com",
        "worker-src 'self' blob:",
        "upgrade-insecure-requests",
    ))
    (output / "_headers").write_text(
        f"/admin.html\n  Content-Security-Policy: {csp}\n",
        encoding="utf-8",
    )
    print(f"Frontend built to {output} with API origin {normalized_origin}")


if __name__ == "__main__":
    main()
